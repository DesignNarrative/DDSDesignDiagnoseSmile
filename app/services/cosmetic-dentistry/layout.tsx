import { Metadata } from "next";
import { getSeoMetadata, getSeoSchemaJson } from "@/lib/seo";

export async function generateMetadata(): Promise<Metadata> {
  return getSeoMetadata("cosmetic-dentistry");
}

export default function CosmeticDentistryLayout({ children }: { children: React.ReactNode }) {
  const schemaJson = getSeoSchemaJson("cosmetic-dentistry");
  return (
    <>
      {schemaJson && (
        <script
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: schemaJson }}
        />
      )}
      {children}
    </>
  );
}
